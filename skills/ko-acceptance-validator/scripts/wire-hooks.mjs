#!/usr/bin/env node
// usage: wire-hooks.mjs <claude-code|omp> [--global] [--build-on <regex>] [--dry-run]
//   Wire this skill's advisory nudge into a coding harness's post-tool hook. Run it with
//   cwd at the repo root. Re-running replaces the earlier wiring.
//     claude-code  merges one PostToolUse entry into .claude/settings.json
//     omp          writes .omp/hooks/post/acceptance-nudge.ts, which omp finds by location
//   --global targets the user's settings instead of this repo's.
//   Exit codes: 0 wired  1 existing settings could not be read  2 bad usage

import { existsSync, mkdirSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

const NUDGE = join(dirname(fileURLToPath(import.meta.url)), "nudge.mjs");
// One matcher for both reminders: plan files written, and commands or skills that end a change.
const CLAUDE_MATCHER = "Write|Edit|MultiEdit|Bash|Skill";
// The regex lands inside a single-quoted shell word in settings.json, so a quote could end it.
const SAFE_BUILD_ON = /^[^'\n]+$/;

// A path from the project root when the skill is installed inside the project, so the wiring
// can be committed and works in any checkout. Otherwise absolute.
function nudgeFromRoot(root) {
  const rel = relative(root, NUDGE);
  return rel.startsWith("..") ? null : rel.split(sep).join("/");
}

function claudeCommand(root, buildOn, global) {
  const rel = global ? null : nudgeFromRoot(root);
  const target = rel ? `\${CLAUDE_PROJECT_DIR:-.}/${rel}` : NUDGE;
  return `node "${target}" claude-code${buildOn ? ` --build-on '${buildOn}'` : ""}`;
}

function wireClaudeCode({ root, global, buildOn }) {
  const file = global ? join(homedir(), ".claude/settings.json") : join(root, ".claude/settings.json");
  let settings = {};
  if (existsSync(file)) {
    try {
      settings = JSON.parse(readFileSync(file, "utf8"));
    } catch (e) {
      throw Object.assign(new Error(`${file} is not valid JSON, so it was left alone: ${e.message}`), { exitCode: 1 });
    }
  }
  const isOurs = (entry) => (entry.hooks ?? []).some((h) => String(h.command).includes("nudge.mjs"));
  const kept = (settings.hooks?.PostToolUse ?? []).filter((entry) => !isOurs(entry));
  const entry = { matcher: CLAUDE_MATCHER, hooks: [{ type: "command", command: claudeCommand(root, buildOn, global) }] };
  const merged = { ...settings, hooks: { ...settings.hooks, PostToolUse: [...kept, entry] } };
  return { file, content: `${JSON.stringify(merged, null, 2)}\n` };
}

function ompHook({ rootRelative, absolute, buildOn }) {
  // omp imports this file directly, so it stays plain JavaScript with no dependency on omp's types.
  const nudgePath = absolute
    ? JSON.stringify(absolute)
    : `decodeURIComponent(new URL(${JSON.stringify(`../../../${rootRelative}`)}, import.meta.url).pathname)`;
  return `// Generated by ko-acceptance-validator's wire-hooks.mjs. Re-run it rather than editing this file.
// Advisory: reminds the agent to run a stage of the skill, and never blocks.
const NUDGE = ${nudgePath};
const BUILD_ON = ${JSON.stringify(buildOn ?? null)};

export default function (pi) {
  pi.on("tool_result", async (event) => {
    if (event.isError) return undefined;
    const args = [NUDGE, "event", "--tool", event.toolName];
    if (["write", "edit"].includes(event.toolName) && event.input?.path) args.push("--path", String(event.input.path));
    else if (event.toolName === "bash" && event.input?.command) args.push("--command", String(event.input.command));
    else return undefined;
    if (BUILD_ON) args.push("--build-on", BUILD_ON);
    try {
      const { stdout } = await pi.exec("node", args);
      const text = stdout.trim();
      return text ? { additionalContext: text } : undefined;
    } catch {
      return undefined;
    }
  });
}
`;
}

function wireOmp({ root, global, buildOn }) {
  const dir = global ? join(homedir(), ".omp/agent/hooks/post") : join(root, ".omp/hooks/post");
  const rootRelative = global ? null : nudgeFromRoot(root);
  const content = ompHook({ rootRelative, absolute: rootRelative ? null : NUDGE, buildOn });
  return { file: join(dir, "acceptance-nudge.ts"), content };
}

const HARNESSES = { "claude-code": wireClaudeCode, omp: wireOmp };

function main(argv) {
  const usage = (message) => {
    process.stderr.write(`${message}\nusage: wire-hooks.mjs <${Object.keys(HARNESSES).join("|")}> [--global] [--build-on <regex>] [--dry-run]\n`);
    return 2;
  };
  let parsed;
  try {
    parsed = parseArgs({
      args: argv,
      allowPositionals: true,
      options: { global: { type: "boolean", default: false }, "build-on": { type: "string" }, "dry-run": { type: "boolean", default: false } },
    });
  } catch (e) {
    return usage(e.message);
  }
  const wire = HARNESSES[parsed.positionals[0]];
  if (!wire) return usage(`unknown harness "${parsed.positionals[0] ?? ""}"`);
  const buildOn = parsed.values["build-on"];
  if (buildOn !== undefined && !SAFE_BUILD_ON.test(buildOn)) return usage("--build-on may not contain a single quote or a newline");

  try {
    const { file, content } = wire({ root: resolve(process.cwd()), global: parsed.values.global, buildOn });
    if (parsed.values["dry-run"]) {
      process.stdout.write(`would write ${file}:\n${content}`);
      return 0;
    }
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, content);
    process.stdout.write(`wired ${parsed.positionals[0]}: ${file}\n`);
    return 0;
  } catch (e) {
    process.stderr.write(`${e.message}\n`);
    return e.exitCode ?? 1;
  }
}

if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) process.exitCode = main(process.argv.slice(2));
